{-# LANGUAGE OverloadedStrings #-}

-- | Deterministic Haskell source generation from validated protocol IR.
module Seki.Scanner.Generate (
  GenerationConfig (..),
  GenerationError (..),
  generateProtocolModule,
  conventionalModuleName,
)
where

import Control.Monad (foldM, unless, void, zipWithM)
import Data.Bifunctor (first)
import Data.Char (isDigit, toLower, toUpper)
import Data.List (find)
import Data.Map.Strict (Map)
import Data.Map.Strict qualified as Map
import Data.Maybe (fromMaybe, isNothing)
import Data.Set (Set)
import Data.Set qualified as Set
import Data.Text (Text)
import Data.Text qualified as Text
import Seki.Scanner.IR (
  Argument (..),
  ArgumentType (..),
  Description (..),
  EnumDefinition (..),
  EnumEntry (..),
  Interface (..),
  Message (..),
  Protocol (..),
 )
import Seki.Scanner.Parse (ScannerError, validateProtocols)

data GenerationConfig = GenerationConfig
  { generationModuleName :: Text
  , generationSourcePath :: Text
  , generationSourcePin :: Text
  }
  deriving (Eq, Show)

data GenerationError
  = GenerationValidationFailed [ScannerError]
  | GenerationTargetNotIncluded Text
  | GenerationUnknownEnumReference Text
  | GenerationUnknownInterfaceReference Text
  | GenerationInvalidHaskellName Text
  | GenerationNameCollision Text
  deriving (Eq, Show)

newtype ProtocolIndex = ProtocolIndex
  { indexedInterfaces :: Map Text (Protocol, Interface)
  }

data EnumTarget = EnumTarget
  { targetProtocol :: Protocol
  , targetInterface :: Interface
  , targetEnum :: EnumDefinition
  }

data ArgumentDirection
  = RequestArgument
  | EventArgument

generateProtocolModule :: GenerationConfig -> [Protocol] -> Protocol -> Either GenerationError Text
generateProtocolModule config protocols target = do
  validated <- first GenerationValidationFailed (validateProtocols protocols)
  unless (protocolName target `elem` map protocolName validated) $
    Left (GenerationTargetNotIncluded (protocolName target))
  let index = makeProtocolIndex validated
  exports <- concat <$> mapM (interfaceExports index target) (protocolInterfaces target)
  ensureUniqueGeneratedNames exports
  foreignModules <- referencedModules index target
  declarations <- concat <$> mapM (renderInterface index target) (protocolInterfaces target)
  pure . Text.unlines $
    renderHeader config target
      <> renderModuleDeclaration config exports
      <> renderImports target foreignModules
      <> renderCopyright target
      <> declarations

conventionalModuleName :: Protocol -> Either GenerationError Text
conventionalModuleName protocol = ("Seki.Protocol." <>) <$> pascalName (protocolName protocol)

makeProtocolIndex :: [Protocol] -> ProtocolIndex
makeProtocolIndex protocols =
  ProtocolIndex
    { indexedInterfaces =
        Map.fromList
          [ (interfaceName interface, (protocol, interface))
          | protocol <- protocols
          , interface <- protocolInterfaces protocol
          ]
    }

renderHeader :: GenerationConfig -> Protocol -> [Text]
renderHeader config protocol =
  [ "{-# LANGUAGE EmptyDataDecls #-}"
  , "{-# LANGUAGE OverloadedStrings #-}"
  , "{-# LANGUAGE PatternSynonyms #-}"
  , ""
  , "-- This file is generated by seki-scanner. Do not edit."
  , "-- Source: " <> singleLine (generationSourcePath config)
  , "-- Pin: " <> singleLine (generationSourcePin config)
  , ""
  ]
    <> renderDescription (protocolDescription protocol)

renderModuleDeclaration :: GenerationConfig -> [Text] -> [Text]
renderModuleDeclaration config exports =
  ["module " <> generationModuleName config <> " ("]
    <> map (("  " <>) . (<> ",")) exports
    <> [")", "where", ""]

renderImports :: Protocol -> Set Text -> [Text]
renderImports protocol foreignModules =
  dataImports
    <> [ "import Seki.Wire.Arguments qualified as Arguments"
       , "import Seki.Wire.Binding qualified as Binding"
       , "import Seki.Wire.Types qualified as Wire"
       ]
    <> map ((<> " qualified") . ("import " <>)) (Set.toAscList foreignModules)
    <> [""]
 where
  arguments = protocolArguments protocol
  types = Set.fromList (map argumentType arguments)
  hasRawInt = any (\argument -> argumentType argument == ArgumentInt && isNothing (argumentEnum argument)) arguments
  hasRawUint = any (\argument -> argumentType argument == ArgumentUint && isNothing (argumentEnum argument)) arguments
  dataImports =
    [ "import Data.ByteString (ByteString)" | ArgumentArray `Set.member` types
    ]
      <> ["import Data.Int (Int32)" | hasRawInt]
      <> ["import Data.Text (Text)" | ArgumentString `Set.member` types]
      <> ["import Data.Word (Word32)" | hasRawUint || not (null (protocolEnums protocol))]

renderCopyright :: Protocol -> [Text]
renderCopyright protocol = case protocolCopyright protocol of
  Nothing -> []
  Just copyrightValue ->
    ["-- Protocol copyright and license text:"]
      <> map commentLine (Text.lines copyrightValue)
      <> [""]

interfaceExports :: ProtocolIndex -> Protocol -> Interface -> Either GenerationError [Text]
interfaceExports index currentProtocol interface = do
  interfaceType <- pascalName (interfaceName interface)
  descriptorName <- lowerName (interfaceName interface) <&> (<> "Interface")
  requestNames <- mapM (requestFunctionName interface) (interfaceRequests interface)
  eventNames <-
    if null (interfaceEvents interface)
      then Right []
      else do
        interfacePrefix <- pascalName (interfaceName interface)
        let eventType = interfaceType <> "Event"
            decoderName = "decode" <> interfacePrefix <> "Event"
        pure [eventType <> " (..)", decoderName]
  enumNames <- concat <$> mapM (enumExports interface) (interfaceEnums interface)
  mapM_ (resolveMessageEnums index currentProtocol interface) (interfaceRequests interface <> interfaceEvents interface)
  pure ([interfaceType, descriptorName] <> requestNames <> eventNames <> enumNames)

requestFunctionName :: Interface -> Message -> Either GenerationError Text
requestFunctionName interface message = do
  interfacePrefix <- pascalName (interfaceName interface)
  messageSuffix <- pascalName (messageName message)
  pure ("encode" <> interfacePrefix <> messageSuffix)

enumExports :: Interface -> EnumDefinition -> Either GenerationError [Text]
enumExports interface enumDefinition = do
  enumType <- enumTypeName interface enumDefinition
  patterns <- mapM (enumPatternName interface enumDefinition) (enumEntries enumDefinition)
  pure ((enumType <> " (..)") : map ("pattern " <>) patterns)

renderInterface :: ProtocolIndex -> Protocol -> Interface -> Either GenerationError [Text]
renderInterface index currentProtocol interface = do
  interfaceType <- pascalName (interfaceName interface)
  descriptorName <- lowerName (interfaceName interface) <&> (<> "Interface")
  requests <- concat <$> mapM (renderRequest index currentProtocol interface) (interfaceRequests interface)
  events <- renderEvents index currentProtocol interface
  enums <- concat <$> mapM (renderEnum interface) (interfaceEnums interface)
  pure $
    renderDescriptionWithDefault
      ("Generated binding marker for @" <> interfaceName interface <> "@.")
      (interfaceDescription interface)
      <> [ "data " <> interfaceType
         , ""
         , "-- | Interface metadata for @" <> interfaceName interface <> "@."
         , descriptorName <> " :: Binding.Interface " <> interfaceType
         , descriptorName
            <> " = Binding.Interface "
            <> haskellString (interfaceName interface)
            <> " "
            <> showText (interfaceVersion interface)
         , ""
         ]
      <> requests
      <> events
      <> enums

renderRequest :: ProtocolIndex -> Protocol -> Interface -> Message -> Either GenerationError [Text]
renderRequest index currentProtocol interface message = do
  functionName <- requestFunctionName interface message
  argumentTypes <- mapM (renderArgumentType index currentProtocol interface RequestArgument) (messageArguments message)
  argumentNames <- mapM argumentValueName (messageArguments message)
  encoders <- zipWithM (renderArgumentEncoder index currentProtocol interface) (messageArguments message) argumentNames
  let signature = Text.intercalate " -> " (argumentTypes <> ["Binding.RequestEncoder fd"])
      definitionHead = Text.unwords (functionName : argumentNames) <> " ="
      constructor =
        "  Binding.RequestEncoder "
          <> haskellString (messageName message)
          <> " (Wire.Opcode "
          <> showText (messageOpcode message)
          <> ") "
          <> showText (messageSince message)
          <> " "
          <> boolText (messageDestructor message)
      body = case encoders of
        [] -> [constructor <> " (pure ())"]
        _ -> [constructor <> " $ do"] <> map ("    " <>) encoders
  pure $
    renderMessageDocumentation "Request" message
      <> [functionName <> " :: " <> signature, definitionHead]
      <> body
      <> [""]

renderEvents :: ProtocolIndex -> Protocol -> Interface -> Either GenerationError [Text]
renderEvents _ _ interface | null (interfaceEvents interface) = Right []
renderEvents index currentProtocol interface = do
  interfaceType <- pascalName (interfaceName interface)
  interfacePrefix <- pascalName (interfaceName interface)
  let decoderName = "decode" <> interfacePrefix <> "Event"
  constructors <- mapM (renderEventConstructor index currentProtocol interface) (interfaceEvents interface)
  decoders <- mapM (renderEventDecoder index currentProtocol interface decoderName) (interfaceEvents interface)
  pure $
    ["-- | Events emitted by @" <> interfaceName interface <> "@.", "data " <> interfaceType <> "Event fd"]
      <> concat (zipWith prefixConstructor [0 :: Int ..] constructors)
      <> [ "  deriving (Eq, Show)"
         , ""
         , decoderName <> " :: Wire.Opcode -> Maybe (Binding.EventDecoder fd (" <> interfaceType <> "Event fd))"
         ]
      <> concat decoders
      <> [decoderName <> " _ = Nothing", ""]
 where
  prefixConstructor position (documentation, constructorLines) =
    let prefix = if position == 0 then "  = " else "  | "
     in case documentation of
          [] -> (prefix <> head constructorLines) : map ("    " <>) (tail constructorLines)
          firstDocumentLine : otherDocumentLines ->
            (prefix <> firstDocumentLine)
              : map ("    " <>) otherDocumentLines
                <> map ("    " <>) constructorLines

renderEventConstructor ::
  ProtocolIndex ->
  Protocol ->
  Interface ->
  Message ->
  Either GenerationError ([Text], [Text])
renderEventConstructor index currentProtocol interface message = do
  constructor <- eventConstructorName interface message
  argumentTypes <- mapM (renderArgumentType index currentProtocol interface EventArgument) (messageArguments message)
  let documentation = renderDescriptionAsConstructor ("Event @" <> messageName message <> "@.") (messageDescription message)
  pure (documentation, constructor : map ("  " <>) argumentTypes)

renderEventDecoder ::
  ProtocolIndex ->
  Protocol ->
  Interface ->
  Text ->
  Message ->
  Either GenerationError [Text]
renderEventDecoder index currentProtocol interface decoderName message = do
  constructor <- eventConstructorName interface message
  decoders <- mapM (renderArgumentDecoder index currentProtocol interface) (messageArguments message)
  newIdExtractor <- renderEventNewIdExtractor constructor (messageArguments message)
  let expression = case decoders of
        [] -> "pure " <> constructor
        firstDecoder : rest -> constructor <> " <$> " <> parenthesize firstDecoder <> foldMap ((" <*> " <>) . parenthesize) rest
  pure
    [ decoderName <> " (Wire.Opcode " <> showText (messageOpcode message) <> ") ="
    , "  Just (Binding.EventDecoder "
        <> haskellString (messageName message)
        <> " "
        <> showText (messageSince message)
        <> " "
        <> boolText (messageDestructor message)
        <> " ("
        <> expression
        <> ") ("
        <> newIdExtractor
        <> "))"
    ]

renderEventNewIdExtractor :: Text -> [Argument] -> Either GenerationError Text
renderEventNewIdExtractor constructor arguments = do
  names <- mapM argumentValueName arguments
  let bindings = zipWith newIdBinding arguments names
      newIds = [newIdExpression argument name | (argument, name) <- zip arguments names, argumentType argument == ArgumentNewId]
  pure $ case newIds of
    [] -> "const []"
    _ ->
      "\\eventValue -> case eventValue of "
        <> Text.unwords (constructor : bindings)
        <> " -> ["
        <> Text.intercalate ", " newIds
        <> "]; _ -> []"
 where
  newIdBinding argument name
    | argumentType argument == ArgumentNewId = name
    | otherwise = "_"
  newIdExpression argument name
    | isNothing (argumentInterface argument) = "Binding.dynamicNewIdObject " <> name
    | otherwise = "Binding.newObjectId " <> name

renderEnum :: Interface -> EnumDefinition -> Either GenerationError [Text]
renderEnum interface enumDefinition = do
  enumType <- enumTypeName interface enumDefinition
  enumValueName <- lowerFirst enumType <&> (<> "Value")
  entries <- concat <$> mapM (renderEnumEntry interface enumDefinition enumType) (enumEntries enumDefinition)
  pure $
    renderDescriptionWithDefault
      ("Values of @" <> interfaceName interface <> "." <> enumName enumDefinition <> "@.")
      (enumDescription enumDefinition)
      <> [ "newtype " <> enumType <> " = " <> enumType
         , "  { " <> enumValueName <> " :: Word32"
         , "  }"
         , "  deriving (Eq, Ord, Show)"
         , ""
         ]
      <> entries

renderEnumEntry :: Interface -> EnumDefinition -> Text -> EnumEntry -> Either GenerationError [Text]
renderEnumEntry interface enumDefinition enumType entry = do
  patternName <- enumPatternName interface enumDefinition entry
  pure $
    renderEntryDocumentation entry
      <> [ "pattern " <> patternName <> " :: " <> enumType
         , "pattern " <> patternName <> " = " <> enumType <> " " <> enumWord32Value (enumEntryValue entry)
         , ""
         ]

renderArgumentType :: ProtocolIndex -> Protocol -> Interface -> ArgumentDirection -> Argument -> Either GenerationError Text
renderArgumentType index currentProtocol currentInterface direction argument = case argumentEnum argument of
  Just reference -> enumReferenceType index currentProtocol currentInterface reference
  Nothing -> rawArgumentType index currentProtocol direction argument

rawArgumentType :: ProtocolIndex -> Protocol -> ArgumentDirection -> Argument -> Either GenerationError Text
rawArgumentType index currentProtocol direction argument = case argumentType argument of
  ArgumentInt -> Right "Int32"
  ArgumentUint -> Right "Word32"
  ArgumentFixed -> Right "Arguments.Fixed"
  ArgumentString -> Right (nullableType "Text")
  ArgumentObject -> Right (nullableType "Wire.ObjectId")
  ArgumentNewId
    | isNothing (argumentInterface argument) -> Right "Binding.DynamicNewId"
    | RequestArgument <- direction -> Right "Wire.ObjectId"
    | Just reference <- argumentInterface argument ->
        (\interfaceType -> "(Binding.NewObject " <> interfaceType <> ")")
          <$> interfaceReferenceType index currentProtocol reference
    | otherwise -> Right "Wire.ObjectId"
  ArgumentArray -> Right "ByteString"
  ArgumentFd -> Right "fd"
 where
  nullableType value
    | argumentNullable argument = "(Maybe " <> value <> ")"
    | otherwise = value

renderArgumentEncoder ::
  ProtocolIndex ->
  Protocol ->
  Interface ->
  Argument ->
  Text ->
  Either GenerationError Text
renderArgumentEncoder index currentProtocol currentInterface argument valueName = case argumentEnum argument of
  Just reference -> do
    enumType <- enumReferenceType index currentProtocol currentInterface reference
    enumValue <- enumValueAccessorName enumType
    let rawValue = enumValue <> " " <> valueName
    pure $ case argumentType argument of
      ArgumentInt -> "Arguments.putInt (fromIntegral (" <> rawValue <> "))"
      _ -> "Arguments.putUint (" <> rawValue <> ")"
  Nothing -> Right $ case argumentType argument of
    ArgumentInt -> "Arguments.putInt " <> valueName
    ArgumentUint -> "Arguments.putUint " <> valueName
    ArgumentFixed -> "Arguments.putFixed " <> valueName
    ArgumentString
      | argumentNullable argument -> "Arguments.putNullableString " <> valueName
      | otherwise -> "Arguments.putString " <> valueName
    ArgumentObject
      | argumentNullable argument -> "Arguments.putNullableObject " <> valueName
      | otherwise -> "Arguments.putObject " <> valueName
    ArgumentNewId
      | isNothing (argumentInterface argument) -> "Binding.putDynamicNewId " <> valueName
      | otherwise -> "Arguments.putNewId " <> valueName
    ArgumentArray -> "Arguments.putArray " <> valueName
    ArgumentFd -> "Arguments.putFd " <> valueName

renderArgumentDecoder :: ProtocolIndex -> Protocol -> Interface -> Argument -> Either GenerationError Text
renderArgumentDecoder index currentProtocol currentInterface argument = case argumentEnum argument of
  Just reference -> do
    enumType <- enumReferenceType index currentProtocol currentInterface reference
    pure $ case argumentType argument of
      ArgumentInt -> enumType <> " . fromIntegral <$> Arguments.getInt"
      _ -> enumType <> " <$> Arguments.getUint"
  Nothing -> Right $ case argumentType argument of
    ArgumentInt -> "Arguments.getInt"
    ArgumentUint -> "Arguments.getUint"
    ArgumentFixed -> "Arguments.getFixed"
    ArgumentString
      | argumentNullable argument -> "Arguments.getNullableString"
      | otherwise -> "Arguments.getString"
    ArgumentObject
      | argumentNullable argument -> "Arguments.getNullableObject"
      | otherwise -> "Arguments.getObject"
    ArgumentNewId
      | isNothing (argumentInterface argument) -> "Binding.getDynamicNewId"
      | otherwise -> "Binding.getNewObject"
    ArgumentArray -> "Arguments.getArray"
    ArgumentFd -> "Arguments.getFd"

enumReferenceType :: ProtocolIndex -> Protocol -> Interface -> Text -> Either GenerationError Text
enumReferenceType index currentProtocol currentInterface reference = do
  target <- resolveEnum index currentInterface reference
  name <- enumTypeName (targetInterface target) (targetEnum target)
  if protocolName (targetProtocol target) == protocolName currentProtocol
    then Right name
    else do
      moduleName <- conventionalModuleName (targetProtocol target)
      pure (moduleName <> "." <> name)

interfaceReferenceType :: ProtocolIndex -> Protocol -> Text -> Either GenerationError Text
interfaceReferenceType index currentProtocol reference = do
  (targetProtocolValue, targetInterfaceValue) <- resolveInterfaceReference index reference
  name <- pascalName (interfaceName targetInterfaceValue)
  if protocolName targetProtocolValue == protocolName currentProtocol
    then Right name
    else do
      moduleName <- conventionalModuleName targetProtocolValue
      pure (moduleName <> "." <> name)

resolveInterfaceReference :: ProtocolIndex -> Text -> Either GenerationError (Protocol, Interface)
resolveInterfaceReference index reference =
  maybe (Left (GenerationUnknownInterfaceReference reference)) Right (Map.lookup reference (indexedInterfaces index))

resolveMessageEnums :: ProtocolIndex -> Protocol -> Interface -> Message -> Either GenerationError ()
resolveMessageEnums index currentProtocol currentInterface message =
  mapM_ resolveArgument (messageArguments message)
 where
  resolveArgument argument = case argumentEnum argument of
    Nothing -> Right ()
    Just reference -> void (enumReferenceType index currentProtocol currentInterface reference)

resolveEnum :: ProtocolIndex -> Interface -> Text -> Either GenerationError EnumTarget
resolveEnum index currentInterface reference = case Text.splitOn "." reference of
  [enumReference] -> makeTarget currentInterface enumReference
  [interfaceReference, enumReference] -> case Map.lookup interfaceReference (indexedInterfaces index) of
    Nothing -> Left (GenerationUnknownEnumReference reference)
    Just (_, interface) -> makeTarget interface enumReference
  _ -> Left (GenerationUnknownEnumReference reference)
 where
  makeTarget interface enumReference = case find ((== enumReference) . enumName) (interfaceEnums interface) of
    Nothing -> Left (GenerationUnknownEnumReference reference)
    Just enumDefinition -> case Map.lookup (interfaceName interface) (indexedInterfaces index) of
      Nothing -> Left (GenerationUnknownEnumReference reference)
      Just (protocol, _) -> Right (EnumTarget protocol interface enumDefinition)

referencedModules :: ProtocolIndex -> Protocol -> Either GenerationError (Set Text)
referencedModules index currentProtocol = do
  enumModules <- foldM addEnumReference Set.empty enumReferences
  foldM addInterfaceReference enumModules interfaceReferences
 where
  enumReferences =
    [ (interface, reference)
    | interface <- protocolInterfaces currentProtocol
    , message <- interfaceRequests interface <> interfaceEvents interface
    , argument <- messageArguments message
    , Just reference <- [argumentEnum argument]
    ]
  interfaceReferences =
    [ reference
    | interface <- protocolInterfaces currentProtocol
    , message <- interfaceEvents interface
    , argument <- messageArguments message
    , argumentType argument == ArgumentNewId
    , Just reference <- [argumentInterface argument]
    ]
  addEnumReference modules (interface, reference) = do
    target <- resolveEnum index interface reference
    if protocolName (targetProtocol target) == protocolName currentProtocol
      then Right modules
      else do
        moduleName <- conventionalModuleName (targetProtocol target)
        Right (Set.insert moduleName modules)
  addInterfaceReference modules reference = do
    (targetProtocolValue, _) <- resolveInterfaceReference index reference
    if protocolName targetProtocolValue == protocolName currentProtocol
      then Right modules
      else do
        moduleName <- conventionalModuleName targetProtocolValue
        Right (Set.insert moduleName modules)

eventConstructorName :: Interface -> Message -> Either GenerationError Text
eventConstructorName interface message =
  (<>) <$> pascalName (interfaceName interface) <*> pascalName (messageName message)

enumTypeName :: Interface -> EnumDefinition -> Either GenerationError Text
enumTypeName interface enumDefinition = do
  interfacePrefix <- pascalName (interfaceName interface)
  enumSuffix <- pascalName (enumName enumDefinition)
  pure (interfacePrefix <> enumSuffix <> if enumBitfield enumDefinition then "Flags" else "Enum")

enumPatternName :: Interface -> EnumDefinition -> EnumEntry -> Either GenerationError Text
enumPatternName interface enumDefinition entry = do
  enumType <- enumTypeName interface enumDefinition
  entrySuffix <- pascalName (enumEntryName entry)
  pure (enumType <> entrySuffix)

argumentValueName :: Argument -> Either GenerationError Text
argumentValueName argument = lowerName (argumentName argument) <&> (<> "Value")

renderMessageDocumentation :: Text -> Message -> [Text]
renderMessageDocumentation kind message =
  renderDescriptionWithDefault
    (kind <> " @" <> messageName message <> "@.")
    (messageDescription message)
    <> argumentDocumentation (messageArguments message)

argumentDocumentation :: [Argument] -> [Text]
argumentDocumentation arguments = case map renderArgument arguments of
  [] -> []
  linesValue -> ["--"] <> linesValue
 where
  renderArgument argument =
    "-- @"
      <> fromMaybe (argumentName argument) (either (const Nothing) (Just . (<> "Value")) (lowerName (argumentName argument)))
      <> "@: "
      <> fromMaybe ("@" <> Text.pack (show (argumentType argument)) <> "@ argument") (argumentSummary argument)

renderDescription :: Maybe Description -> [Text]
renderDescription = renderDescriptionWithDefault "Generated Wayland protocol bindings."

renderDescriptionWithDefault :: Text -> Maybe Description -> [Text]
renderDescriptionWithDefault defaultSummary description = case description of
  Nothing -> ["-- | " <> singleLine defaultSummary]
  Just value ->
    ["-- | " <> singleLine (descriptionSummary value)]
      <> bodyComments (descriptionBody value)

renderDescriptionAsConstructor :: Text -> Maybe Description -> [Text]
renderDescriptionAsConstructor defaultSummary description = case description of
  Nothing -> ["-- | " <> singleLine defaultSummary]
  Just value ->
    ["-- | " <> singleLine (descriptionSummary value)]
      <> bodyComments (descriptionBody value)

renderEntryDocumentation :: EnumEntry -> [Text]
renderEntryDocumentation entry = case enumEntryDescription entry of
  Just description -> renderDescriptionWithDefault fallback (Just description)
  Nothing -> ["-- | " <> singleLine fallback]
 where
  fallback = fromMaybe ("Enum entry @" <> enumEntryName entry <> "@.") (enumEntrySummary entry)

bodyComments :: Text -> [Text]
bodyComments body
  | Text.null body = []
  | otherwise = ["--"] <> map commentLine (Text.lines body)

commentLine :: Text -> Text
commentLine line
  | Text.null line = "--"
  | otherwise = "-- " <> line

pascalName :: Text -> Either GenerationError Text
pascalName source = case filter (not . Text.null) (Text.splitOn "_" source) of
  [] -> Left (GenerationInvalidHaskellName source)
  parts -> do
    let result = Text.concat (map capitalize parts)
    if Text.null result
      then Left (GenerationInvalidHaskellName source)
      else Right result
 where
  capitalize part = case Text.uncons part of
    Nothing -> ""
    Just (firstCharacter, rest)
      | isDigit firstCharacter -> "N" <> part
      | otherwise -> Text.cons (toUpper firstCharacter) rest

lowerName :: Text -> Either GenerationError Text
lowerName source = pascalName source >>= lowerFirst

lowerFirst :: Text -> Either GenerationError Text
lowerFirst value = case Text.uncons value of
  Nothing -> Left (GenerationInvalidHaskellName value)
  Just (firstCharacter, rest) -> Right (Text.cons (toLower firstCharacter) rest)

enumValueAccessorName :: Text -> Either GenerationError Text
enumValueAccessorName enumType = case reverse (Text.splitOn "." enumType) of
  [] -> Left (GenerationInvalidHaskellName enumType)
  localType : reversedModuleParts -> do
    localAccessor <- lowerFirst localType <&> (<> "Value")
    let moduleName = Text.intercalate "." (reverse reversedModuleParts)
    pure $ if Text.null moduleName then localAccessor else moduleName <> "." <> localAccessor

ensureUniqueGeneratedNames :: [Text] -> Either GenerationError ()
ensureUniqueGeneratedNames names = case firstDuplicate names of
  Nothing -> Right ()
  Just duplicate -> Left (GenerationNameCollision duplicate)

firstDuplicate :: (Ord value) => [value] -> Maybe value
firstDuplicate = go Set.empty
 where
  go _ [] = Nothing
  go seen (value : rest)
    | value `Set.member` seen = Just value
    | otherwise = go (Set.insert value seen) rest

protocolArguments :: Protocol -> [Argument]
protocolArguments protocol =
  [ argument
  | interface <- protocolInterfaces protocol
  , message <- interfaceRequests interface <> interfaceEvents interface
  , argument <- messageArguments message
  ]

protocolEnums :: Protocol -> [EnumDefinition]
protocolEnums protocol = concatMap interfaceEnums (protocolInterfaces protocol)

enumWord32Value :: Integer -> Text
enumWord32Value value = showText (value `mod` 4294967296)

haskellString :: Text -> Text
haskellString = Text.pack . show . Text.unpack

singleLine :: Text -> Text
singleLine = Text.unwords . Text.words

showText :: (Show value) => value -> Text
showText = Text.pack . show

boolText :: Bool -> Text
boolText True = "True"
boolText False = "False"

parenthesize :: Text -> Text
parenthesize value = "(" <> value <> ")"

infixl 4 <&>

(<&>) :: (Functor functor) => functor value -> (value -> result) -> functor result
(<&>) = flip fmap
